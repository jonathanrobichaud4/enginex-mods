#!/usr/bin/env python3
"""Generates assets.h for sc-diagnostics:
  - the SC LIVE 4 control layout and MIDI map, from the emulator's panel.json (which mirrors
    Engine's own JP21 assignment file), and
  - DejaVu Sans Bold glyphs for printable ASCII at three sizes, as 8-bit coverage bitmaps
    (DejaVu fonts: Bitstream Vera license, free to embed).
Usage: gen_assets.py panel.json DejaVuSans-Bold.ttf > assets.h"""
import json, sys
from PIL import Image, ImageDraw, ImageFont

panel, ttf = sys.argv[1], sys.argv[2]
p = json.load(open(panel))
types = {"btn": 0, "pad": 1, "knob": 2, "fader": 3, "xfader": 4, "enc": 5, "jog": 6, "pitch": 7, "sw": 8, "sel": 9, "vu": 10}
out = ["/* generated by gen_assets.py: do not edit */", "#include <stdint.h>",
       "typedef struct { uint8_t type, ch; int16_t n, cc, cc2, extra; int16_t x, y, w, h; uint8_t round; const char *id, *lab; } ctl_t;",
       f"enum {{ PANEL_W = {p['w']}, PANEL_H = {p['h']} }};",
       "static const ctl_t CTLS[] = {"]
for c in p["controls"]:
    t = c.get("t")
    if t not in types:
        continue
    n = c.get("n", c.get("push", c.get("touch", -1)))
    extra = c.get("led", -1)
    lab = (c.get("lab") or c["id"]).replace('"', "'")
    out.append(f'  {{{types[t]}, {c["ch"]}, {n}, {c.get("cc", -1)}, {c.get("cc2", -1)}, {extra}, '
               f'{int(c["x"])}, {int(c["y"])}, {int(c["w"])}, {int(c["h"])}, {1 if c.get("round") else 0}, "{c["id"]}", "{lab}"}},')
out.append("};")
out.append("#define NCTLS (int)(sizeof CTLS / sizeof CTLS[0])")
# panel labels and outlines, for the controls map
out.append("typedef struct { int16_t x, y, w, h; const char *lab; } deco_t;")
out.append("static const deco_t DECOS[] = {")
for c in p["controls"]:
    if c.get("t") in ("label", "panel", "screen"):
        out.append(f'  {{{int(c["x"])}, {int(c["y"])}, {int(c["w"])}, {int(c["h"])}, "{(c.get("lab") or "").replace(chr(34), chr(39))}"}},')
out.append("};")
out.append("#define NDECOS (int)(sizeof DECOS / sizeof DECOS[0])")

out.append("typedef struct { uint8_t w, h, adv; int8_t top; uint32_t off; } glyph_t;")
for name, size in (("S", 13), ("M", 20), ("L", 34)):
    font = ImageFont.truetype(ttf, size)
    asc, desc = font.getmetrics()
    data, glyphs = [], []
    for code in range(32, 127):
        ch = chr(code)
        adv = int(round(font.getlength(ch)))
        box = font.getbbox(ch)
        w, h = max(0, box[2] - box[0]), max(0, box[3] - box[1])
        if w == 0 or h == 0:
            glyphs.append((0, 0, adv, 0, len(data)))
            continue
        im = Image.new("L", (w, h), 0)
        ImageDraw.Draw(im).text((-box[0], -box[1]), ch, font=font, fill=255)
        glyphs.append((w, h, adv, box[1], len(data)))
        data.extend(im.tobytes())
    out.append(f"enum {{ FONT{name}_ASC = {asc}, FONT{name}_H = {asc + desc} }};")
    out.append(f"static const glyph_t FONT{name}_G[95] = {{" + ",".join(f"{{{w},{h},{a},{t},{o}}}" for w, h, a, t, o in glyphs) + "};")
    rows = [",".join(str(b) for b in data[i:i + 40]) for i in range(0, len(data), 40)]
    out.append(f"static const uint8_t FONT{name}_D[] = {{\n" + ",\n".join(rows) + "};")
print("\n".join(out))
